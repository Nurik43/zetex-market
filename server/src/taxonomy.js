export const CATEGORIES = TAXONOMY.map((c) => c.name);

/** Проверка: подкатегория принадлежит категории (пустая допустима). */
export function isValidSub(category, sub) {
  if (!sub) return true;
  const c = TAXONOMY.find((x) => x.name === category);
  return !!c && c.groups.some((g) => g.items.includes(sub));
}

